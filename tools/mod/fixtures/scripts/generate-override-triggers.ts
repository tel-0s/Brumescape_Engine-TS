// Regenerates override_triggers/scripts/all_triggers.rs2 for the scripts fixture:
//
//   bun run tools/mod/fixtures/scripts/generate-override-triggers.ts
//
// For every trigger type that base content uses, it overrides one base script
// that jumps to its original (@), and, when the trigger has another script
// that does not jump to labels, one script that calls its original (~) and
// then runs more code. Scripts that the other fixture mods override are
// skipped. Run it again when base content changes and a picked script is gone.

import fs from 'fs';
import path from 'path';

import { findLabelJumps, parseSignature, scanScriptBlocks, splitSourceLines } from '#/mod/RuneScriptSource.js';
import Environment from '#/util/Environment.js';

const OUTPUT = 'tools/mod/fixtures/scripts/override_triggers/scripts/all_triggers.rs2';
// overridden by override_demo / override_chain
const SKIP = new Set(['[opnpc1,hans]', '[proc,count_questpoints]', '[proc,update_questlist]', '[login,_]', '[logout,_]', '[opheld1,thkebabinstructs]', '[opnpc1,_citizen]', '[opnpc3,zaff]']);

interface Candidate {
    file: string;
    name: string;
    trigger: string;
    subject: string;
    rest: string;
    jumps: boolean;
}

const root = path.resolve(Environment.BUILD_SRC_DIR, 'scripts');
const files: string[] = [];
const walk = (dir: string) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : 1))) {
        const full = path.join(dir, entry.name);
        if (entry.isDirectory()) {
            walk(full);
        } else if (full.endsWith('.rs2') && full !== path.join(root, 'engine.rs2')) {
            files.push(full);
        }
    }
};
walk(root);

const byTrigger = new Map<string, Candidate[]>();
for (const file of files) {
    const lines = splitSourceLines(fs.readFileSync(file, 'utf-8'));
    for (const block of scanScriptBlocks(lines)) {
        if (SKIP.has(block.name)) {
            continue;
        }
        let list = byTrigger.get(block.trigger);
        if (!list) {
            list = [];
            byTrigger.set(block.trigger, list);
        }
        list.push({ file: path.relative(root, file), name: block.name, trigger: block.trigger, subject: block.subject, rest: block.rest, jumps: findLabelJumps(lines, block).length > 0 });
    }
}

// prefer scripts outside _test/
const pick = (list: Candidate[], test: (c: Candidate) => boolean) => list.find(c => !c.file.startsWith('_test/') && test(c)) ?? list.find(test);

// header with the same signature, parameters renamed $p0, $p1, ...
function header(c: Candidate) {
    const signature = c.rest.startsWith('(') ? parseSignature(c.rest) : null;
    const params = signature ? `(${signature.params.map((type, i) => `${type} $p${i}`).join(', ')})${signature.returns.length > 0 ? `(${signature.returns.join(', ')})` : ''}` : '';
    const args = signature && signature.params.length > 0 ? `(${signature.params.map((_, i) => `$p${i}`).join(', ')})` : '';
    return { text: `${c.name}${params}`, args, returns: (signature?.returns.length ?? 0) > 0 };
}

const out = [
    '// GENERATED by tools/mod/fixtures/scripts/generate-override-triggers.ts: one',
    '// override per trigger type that base content uses. Each one jumps to (@) or',
    '// calls (~) the original that it replaces. check.ts reads this file.',
    ''
];

for (const [trigger, list] of Array.from(byTrigger.entries()).sort((a, b) => (a[0] < b[0] ? -1 : 1))) {
    const original = (c: Candidate) => `original_${c.trigger}_${c.subject}`;
    const first = pick(list, () => true)!;
    const h = header(first);
    if (first.trigger === 'proc' || h.returns) {
        out.push(h.text, h.returns ? `return(~${original(first)}${h.args});` : `~${original(first)}${h.args};`, '');
        continue;
    }
    out.push(h.text, `@${original(first)}${h.args};`, '');

    const second = pick(list, c => c !== first && !c.jumps);
    if (second) {
        const h2 = header(second);
        out.push(h2.text, `~${original(second)}${h2.args};`, `def_int $after_${trigger} = 1;`, '');
    }
}

fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
fs.writeFileSync(OUTPUT, out.join('\n'));
console.log(`wrote ${OUTPUT} (${byTrigger.size} trigger types)`);
